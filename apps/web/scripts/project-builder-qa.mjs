import { chromium, expect } from "@playwright/test";
import fs from "node:fs/promises";
import path from "node:path";
import { openQaSession } from "./qa-session.mjs";

const output = path.resolve("evals/reports/project-builder");
await fs.mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1536, height: 1000 }, reducedMotion: "reduce" });
const report = { checks: [], errors: [], note: "Authenticated local API persistence checks. The automatic AI planning endpoint is deliberately held unavailable for this UI test, to test recovery without starting generation. Real model planning is verified separately." };
page.on("pageerror", e => report.errors.push(e.message));
const check = label => { report.checks.push(label); console.log("PASS", label); };
let api, project;
try {
  const session = await openQaSession(page);
  api = Object.fromEntries(["get", "post", "patch"].map(method => [method, (url, options) => session.api[method](session.base + url, options)]));
  await page.route("**/plan-refinement", route => route.fulfill({ status: 503, json: { detail: "QA: provider temporarily unavailable" } }));
  const response = await api.post("/v1/projects", { data: { name: `Builder QA ${Date.now()}` } });
  expect(response.ok()).toBeTruthy(); project = await response.json();
  await page.reload();
  await page.getByRole("button", { name: project.name, exact: true }).click();
  await expect(page.getByRole("heading", { name: "Big idea? Start with a small step." })).toBeVisible();
  check("Every new project exposes its task board and design before chats");
  await page.getByRole("button", { name: "New conversation", exact: true }).click();
  await page.getByRole("textbox", { name: "Describe your request" }).fill("I'd like to make a 2D browser game where a little fox collects stars and rescues lost owls. I am a beginner and want to keep it free.");
  await page.getByRole("textbox", { name: "Describe your request" }).press("Enter");
  await expect(page.locator(".bsetup-extracted")).toContainText("2D");
  await expect(page.locator(".bsetup-extracted")).toContainText(/browser/i);
  await page.screenshot({ path: path.join(output, "setup-desktop.png") });
  check("First creation prompt opens setup and carries 2D/browser/beginner/free choices forward");
  await page.getByRole("button", { name: /Use recommendations for the remaining choices/ }).click();
  await expect(page.getByRole("heading", { name: "In your project sidebar" })).toBeVisible();
  await page.getByRole("button", { name: "Create my roadmap", exact: true }).click();
  await expect(page.getByRole("heading", { name: "From idea to made it." })).toBeVisible();
  await expect(page.locator(".builder-task").first()).toBeVisible();
  await page.screenshot({ path: path.join(output, "board-desktop.png") });
  const first = await (await api.get(`/v1/projects/${project.id}/workspace`)).json();
  expect(first.workspace.initialized).toBeTruthy(); expect(first.workspace.kind).toBe("game");
  expect(first.workspace.answers.dimension).toBe("2d"); expect(first.workspace.answers.platform).toBe("web");
  expect(first.workspace.tasks.length).toBeGreaterThan(10);
  expect(first.workspace.components).toContain("game-design");
  check("Roadmap, answers, editor components and task acceptance criteria persist to the live API");
  await page.getByRole("button", { name: "Dismiss error" }).click().catch(() => {});
  await page.getByRole("button", { name: "Add task", exact: true }).click();
  await page.getByLabel("Task title", { exact: true }).fill("Make the fox jump over a log");
  await page.getByLabel("What needs to happen?").fill("Space jumps; landing returns the fox to a stable ground position.");
  await page.getByLabel(/Done when/).fill("A child can jump using the keyboard\nThe fox lands without falling through the ground");
  await page.getByRole("button", { name: "Save task", exact: true }).click();
  await expect(page.getByRole("button", { name: /Make the fox jump over a log/ })).toBeVisible();
  await page.getByRole("button", { name: /Make the fox jump over a log/ }).click();
  await page.getByLabel(/^Status/).selectOption("doing");
  await page.getByRole("button", { name: "Save task", exact: true }).click();
  await expect(page.getByRole("region", { name: "In progress", exact: true }).getByText("Make the fox jump over a log")).toBeVisible();
  check("Task creation, acceptance checks and keyboard-accessible status moves work");
  await page.getByRole("button", { name: "Project Blueprint", exact: true }).click();
  await page.getByRole("button", { name: "Edit design", exact: true }).click();
  const design = page.getByRole("textbox", { name: "Project design content" });
  await design.fill((await design.inputValue()) + "\n\n## Playtest note\nA five-minute fox rescue is the first milestone.\n");
  page.once("dialog", dialog => dialog.dismiss());
  await page.getByRole("button", { name: "Task Board", exact: true }).click();
  await expect(design).toBeVisible();
  check("Switching tools protects unsaved design edits");
  await page.getByRole("button", { name: "Save design", exact: true }).click();
  await expect(page.locator(".builder-document")).toContainText("A five-minute fox rescue");
  await page.reload();
  await page.getByRole("button", { name: project.name, exact: true }).click();
  await expect(page.getByRole("region", { name: "In progress", exact: true }).getByText("Make the fox jump over a log")).toBeVisible();
  check("Saved tasks and edited design survive a full browser reload");
  const preview = await (await api.post(`/v1/projects/${project.id}/plan-preview`, { data: { prompt: "I want to build a game with dragons" } })).json();
  expect(preview.eligible).toBe(false); expect(preview.reason).toBe("already_planned");
  check("Follow-up creation language cannot restart an initialized roadmap");
  const projectChats = await (await api.get(`/v1/chats?project_id=${project.id}`)).json();
  const archivedChat = projectChats[0];
  expect(archivedChat).toBeTruthy();
  await api.patch(`/v1/chats/${archivedChat.id}`, { data: { archived: true } });
  await page.reload();
  await page.getByRole("button", { name: "Archive", exact: true }).click();
  await expect(page.getByRole("button", { name: archivedChat.title, exact: true })).toBeVisible();
  check("Archived chats remain reachable beneath an active project");
  await api.patch(`/v1/chats/${archivedChat.id}`, { data: { archived: false } });
  await page.getByRole("button", { name: "Back to workspace", exact: true }).click();
  await page.getByRole("button", { name: project.name, exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: path.join(output, "board-phone.png"), fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await page.getByRole("button", { name: "Review project setup", exact: true }).click();
  await expect(page.locator(".bsetup-question")).toBeVisible();
  await page.screenshot({ path: path.join(output, "setup-phone.png"), fullPage: true });
  await page.setViewportSize({ width: 320, height: 720 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await page.screenshot({ path: path.join(output, "setup-320.png"), fullPage: true });
  check("Setup and task board reflow at 390px and 320px without page overflow");
  expect(report.errors).toEqual([]);
} finally {
  await page.screenshot({ path: path.join(output, "last-state.png"), fullPage: true }).catch(() => {});
  if (api && project) await api.patch(`/v1/projects/${project.id}`, { data: { archived: true } });
  await fs.writeFile(path.join(output, "report.json"), JSON.stringify(report, null, 2));
  await browser.close();
}

